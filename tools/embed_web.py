# PlatformIO pre-build step: gzip web/*.html into src/web_assets.h so the
# pages are served compressed straight from flash.
import gzip, os, re

try:
    Import("env")  # noqa: F821  (provided by PlatformIO)
    root = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

web = os.path.join(root, "web")
out = os.path.join(root, "src", "web_assets.h")
parts = ["// Generated by tools/embed_web.py from web/*.html - do not edit.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n"]
for name in sorted(os.listdir(web)):
    if not name.endswith(".html"):
        continue
    raw = open(os.path.join(web, name), "rb").read()
    data = gzip.compress(raw, 9, mtime=0)
    ident = re.sub(r"\W", "_", name).upper() + "_GZ"
    body = ",".join(str(b) for b in data)
    parts.append(f"static const uint8_t {ident}[] = {{{body}}};\nstatic const size_t {ident}_LEN = {len(data)};\n")
text = "".join(parts)
if not os.path.exists(out) or open(out).read() != text:
    open(out, "w").write(text)
    print("embed_web: updated", out)
